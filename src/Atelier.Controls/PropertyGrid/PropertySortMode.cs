namespace Atelier.Controls;

/// <summary>
/// Specifies the display sort mode for properties in a <see cref="PropertyGrid"/>.
/// </summary>
public enum PropertySortMode
{
    /// <summary>
    /// Properties are grouped by category into collapsible sections.
    /// </summary>
    Categorized,

    /// <summary>
    /// Properties are sorted alphabetically by display name in a flat list.
    /// </summary>
    Alphabetical
}
